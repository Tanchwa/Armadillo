// The shape apparmor-profile-action emits.
const actionProfile = `# AppArmor profile for myapp
# Generated by apparmor-profile-action (runtime learning).

include <tunables/global>

profile myapp flags=(attach_disconnected,mediate_deleted) {
  include <abstractions/base>

  # Container baseline
  deny @{PROC}/sys/kernel/{,**} wklx,
  deny mount,

  capability chown,
  network inet stream,
  "/etc/myapp/config.yaml" r,
}
`

func TestRenderActionProfile(t *testing.T) {
	got, err := Render(actionProfile, "armadillo.shop.myapp", Complain)
	if err != nil {
		t.Fatal(err)
	}
	want := `include <tunables/global>

profile armadillo.shop.myapp flags=(attach_disconnected,mediate_deleted,complain) {
  include <abstractions/base>
  deny @{PROC}/sys/kernel/{,**} wklx,
  deny mount,
  capability chown,
  network inet stream,
  "/etc/myapp/config.yaml" r,
}
`
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}

	enforce, err := Render(actionProfile, "armadillo.shop.myapp", Enforce)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(enforce, "complain") {
		t.Errorf("enforce render still carries complain:\n%s", enforce)
	}
}

func TestRenderIgnoresNameAndFlagsInText(t *testing.T) {
	for _, header := range []string{
		"profile cri-containerd.apparmor.d flags=(complain) {",
		"profile x flags=(unconfined) {",
		"/usr/bin/kubelet {",
		`profile "name with space" {`,
	} {
		got, err := Render(header+"\n  /tmp/x r,\n}\n", "armadillo.ns.p", Enforce)
		if err != nil {
			t.Errorf("%q: %v", header, err)
			continue
		}
		want := "profile armadillo.ns.p flags=(attach_disconnected,mediate_deleted) {\n  /tmp/x r,\n}\n"
		if got != want {
			t.Errorf("%q: got:\n%s", header, got)
		}
	}
}

func TestRenderRejects(t *testing.T) {
	cases := map[string]string{
		"attachment":         "profile x /usr/bin/kubelet {\n}\n",
		"two profiles":       "profile a {\n}\nprofile b {\n}\n",
		"child profile":      "profile a {\n  profile b {\n  }\n}\n",
		"hat":                "profile a {\n  ^hat {\n  }\n}\n",
		"quoted include":     "profile a {\n  include \"/etc/shadow\"\n}\n",
		"hash quoted":        "profile a {\n  #include \"/etc/shadow\"\n}\n",
		"absolute include":   "profile a {\n  include </etc/shadow>\n}\n",
		"include traversal":  "profile a {\n  include <abstractions/../../shadow>\n}\n",
		"include if exists":  "profile a {\n  include if exists <local/x>\n}\n",
		"include in comment": "profile a {\n  # include \"/etc/shadow\"\n}\n",
		"variable preamble":  "@{x}=/etc\nprofile a {\n}\n",
		"unclosed":           "profile a {\n  /tmp/x r,\n",
		"empty":              "# nothing here\n",
		"trailing rule":      "profile a {\n}\n/etc/shadow r,\n",
		"smuggled profile":   "profile a {\n  } profile evil /usr/bin/kubelet { /** rwix,\n}\n",
		"smuggled no space":  "profile a {\n  foo} profile evil{ /** rwix,\n}\n",
		"close and reopen":   "profile a {\n  /x}{y r,\n}\n",
	}
	for name, text := range cases {
		if out, err := Render(text, "armadillo.ns.p", Enforce); err == nil {
			t.Errorf("%s: accepted, rendered:\n%s", name, out)
		}
	}
	if _, err := Render(strings.Repeat("#", MaxProfileBytes+1), "n", Enforce); err == nil {
		t.Error("oversized profile accepted")
	}
	if _, err := Render("profile a {\n}\n", "n", Mode("Kill")); err == nil {
		t.Error("unknown mode accepted")
	}
}

func TestProfileNameAndHash(t *testing.T) {
	if got := ProfileName("shop", "my.app"); got != "armadillo.shop.my.app" {
		t.Error(got)
	}
	if got := Hash("abc"); got != "sha256:ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad" {
		t.Error(got)
	}
}
